const NOW = new Date('2026-07-27T21:00:00.000Z');

// Helper to construct ISO strings relative to NOW
export function getRelativeISO(minutesOffset: number): string {
  const d = new Date(NOW.getTime() + minutesOffset * 60 * 1000);
  return d.toISOString();
}

